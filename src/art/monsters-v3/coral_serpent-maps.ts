export type StillPart = 't' | 'f' | 'a' | 'c' | 'h' | 'j' | 'm' | 'd';

/** The still's colour at a v1-frame pixel (null = empty). */
export function stillAt(x: number, y: number): number | null {
  const row = SERPENT_MAP[y];
  if (!row || x < 0 || x >= row.length) return null;
  const ch = row[x];
  if (ch === '.') return null;
  const c = SERPENT_KEY[ch];
  if (c === undefined) throw new Error(`serpent-map: unknown pixel '${ch}' at ${x},${y}`);
  return c;
}

/** The part a v1-frame pixel belongs to at rest ('o' outline, '.' empty). */
export function ownerAt(x: number, y: number): string {
  return OWNER[y]?.[x] ?? '.';
}

export interface PartPixels {
  /** v1-frame coordinates and still colours of the part's pixels */
  readonly xs: Int16Array;
  readonly ys: Int16Array;
  readonly cols: Int32Array;
  readonly n: number;
  /** bounding box (v1 frame px) */
  readonly x0: number;
  readonly y0: number;
  readonly x1: number;
  readonly y1: number;
}

const parts = new Map<string, PartPixels>();

/** The still's pixels of one part (or of several: codes concatenated), cut lazily and cached. */
export function partPixels(codes: string): PartPixels {
  let p = parts.get(codes);
  if (p) return p;
  const xs: number[] = [];
  const ys: number[] = [];
  const cols: number[] = [];
  let x0 = 1e9;
  let y0 = 1e9;
  let x1 = -1;
  let y1 = -1;
  for (let y = 0; y < OWNER.length; y++)
    for (let x = 0; x < OWNER[y].length; x++) {
      if (!codes.includes(OWNER[y][x])) continue;
      const c = stillAt(x, y);
      if (c === null) throw new Error(`coral_serpent-maps: OWNER ${OWNER[y][x]} at ${x},${y} is empty in the still`);
      xs.push(x);
      ys.push(y);
      cols.push(c);
      if (x < x0) x0 = x;
      if (x > x1) x1 = x;
      if (y < y0) y0 = y;
      if (y > y1) y1 = y;
    }
  p = Object.freeze({ xs: Int16Array.from(xs), ys: Int16Array.from(ys), cols: Int32Array.from(cols), n: xs.length, x0, y0, x1, y1 });
  parts.set(codes, p);
  return p;
}
